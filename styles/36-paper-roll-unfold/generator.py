# Regenerates template/compositions/pr1.html. Edit SHEETS (one word or short line each), then run:
#   python3 generator.py && python3 ../../tools/build_index.py template
import pathlib
SHEETS = [("LOREM", "sans"), ("ipsum", "serif"), ("DOLOR", "sans"), ("sit amet", "serif")]
SH = 300                        # height of one "sheet" of text (px)
H = 12                          # slice height: smaller = smoother curl, heavier page
R = pathlib.Path(__file__).resolve().parent / "template"
L = SH * len(SHEETS); N = L // H
sheet_html = "".join(f'<div class="sh" style="top:{i*SH}px"><span class="{k}">{w}</span></div>' for i, (w, k) in enumerate(SHEETS))
slices = "\n".join(f'      <div id="pr1-s{i}" class="sl" data-layout-allow-overflow data-layout-allow-overlap style="top:{i*H}px"><div class="strip" data-layout-ignore style="top:{-i*H}px">{sheet_html}</div></div>' for i in range(N))
html = """<template>
  <style>
    @font-face { font-family: "Instrument Serif"; font-style: italic; src: url("assets/fonts/instrument-serif-italic.woff2") format("woff2"); }
    #pr1 { position: absolute; inset: 0; overflow: hidden; perspective: 1600px; perspective-origin: 540px 700px;
      background: radial-gradient(ellipse 85% 60% at 50% 40%, var(--stageLight, #efeafc) 0%, var(--stageDeep, #b9aee3) 100%); }
    /* NO paper, NO roll: the column of words itself is the strip. It is cut into thin horizontal slices; slices past
       the curl line wrap around a horizontal axis, so the words roll up like a paper roll and unroll top to bottom. */
    #pr1-col { position: absolute; left: 140px; top: 240px; width: 800px; height: """ + str(L) + """px; transform-style: preserve-3d; }
    #pr1 .sl { position: absolute; left: 0; width: 800px; height: """ + f"{H + 3}" + """px; overflow: hidden; transform-origin: 50% 0; }
    #pr1 .strip { position: absolute; left: 0; width: 800px; height: """ + str(L) + """px; }
    #pr1 .sh { position: absolute; left: 0; width: 800px; height: """ + str(SH) + """px; display: flex; align-items: center; justify-content: center; }
    #pr1 .sans { font: 400 190px/1 "Archivo Black", sans-serif; letter-spacing: -0.04em; color: var(--c1, #2f55ff); }
    #pr1 .serif { font: italic 400 230px/1 "Instrument Serif", serif; color: var(--c2, #e0219b); }
  </style>
  <div id="pr1" data-composition-id="pr1" data-width="1080" data-height="1920">
    <!-- generated by generator.py: edit SHEETS there (every slice carries a copy of the words) -->
    <div id="pr1-col" data-layout-allow-overlap data-layout-allow-overflow>
""" + slices + """
    </div>
  </div>
  <script>
    const tl = gsap.timeline({ paused: true });
    // Slice i covers strip length s = i·H. The curl line sits at strip length C. Above it the words lie flat; past it
    // they wind round a roll of radius r that hangs just below the curl line and turns AWAY from camera (like paper
    // coming off the back of a roll). Only the outer turn shows; the side facing away is dimmed and mirrored,
    // so the roll reads as a see-through cylinder made of letters.
    const N = """ + str(N) + """, H = """ + str(H) + """, L = """ + str(L) + """;
    const S = [...Array(N).keys()].map(i => document.getElementById("pr1-s" + i));
    const st = { c: 0, r: 120, fade: 0 };
    function render() {
      const C = st.c, r = st.r;
      for (let i = 0; i < N; i++) {
        const s = i * H, u = s - C;                       // how far past the curl line this slice is (along the strip)
        let y = s, z = 0, rx = 0, op = st.fade, dim = 1;
        if (u > 0) {
          const phi = u / r;                              // angle round the roll
          if (phi > 2 * Math.PI) { op = 0; }              // inner turns are hidden: only the outer turn shows
          y = C + r * Math.sin(phi); z = -r + r * Math.cos(phi); rx = phi * 180 / Math.PI;
          if (Math.cos(phi) < 0) dim = 0.38;              // far side of the roll: dim (see-through)
        }
        S[i].style.transform = `translate3d(0, ${(y - s).toFixed(2)}px, ${z.toFixed(2)}px) rotateX(${rx.toFixed(2)}deg)`;
        S[i].style.opacity = op * dim;
      }
    }
    // APPEAR: the tightly rolled words fade in at the top
    tl.fromTo(st, { c: 0, r: 120, fade: 0 }, { fade: 1, duration: 0.4, ease: "power2.out", onUpdate: render }, 0);
    tl.fromTo("#pr1-col", { y: -40 }, { y: 0, duration: 0.5, ease: "back.out(2)" }, 0);
    // UNROLL: the curl line travels down the column and the roll thins as the words come off it
    tl.to(st, { c: L, r: 40, duration: 3.0, ease: "power1.inOut", onUpdate: render }, 0.45);
    // HOLD, then ROLL BACK UP quickly from the bottom and vanish
    tl.to(st, { c: 0, r: 110, duration: 0.8, ease: "power3.in", onUpdate: render }, 4.3);
    tl.to(st, { fade: 0, duration: 0.25, onUpdate: render }, 5.05);
    render();
    window.__timelines["pr1"] = tl;
  </script>
</template>
"""
(R / "compositions/pr1.html").write_text(html)
print("wrote", R / "compositions/pr1.html", N, "slices")
